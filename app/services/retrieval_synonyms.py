def expand_synonyms(term: str) -> list[str]:
    """Return the original term plus any known synonyms."""
    result = [term]
    aliases = SYNONYM_DICT.get(term, [])
    for alias in aliases:
        if alias not in result:
            result.append(alias)
    return result
